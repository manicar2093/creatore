package main

import (
	"fmt"
	. "github.com/dave/jennifer/jen"
	"os"
)

const (
	ctxKeyword = "ctx"
	reqKeyword = "req"
	resKeyword = "res"
)

func createControllerFile(data usefulData) error {
	jf := NewFile(data.modelsKey)
	jf.ImportAlias("github.com/labstack/echo/v4", "echo")
	jf.PackageComment("Code generated by creatore")

	jf.Add(generateControllerCode(data))

	return jf.Render(os.Stdout)
}

func generateControllerCode(input usefulData) Code {
	return Null().
		Add(generateControllerStruct(input)).
		Line().
		Line().
		Add(generateControllerConstructor(input)).
		Line().
		Line().
		Add(generateControllerSaveMethod(input)).
		Line().
		Line().
		Add(generateControllerGetById(input)).
		Line().
		Line().
		Add(generateControllerGetAllPaginatedMethods(input))
}

func generateControllerStruct(input usefulData) Code {
	return Null().
		Type().
		Id(input.controllerStructName).
		Struct(
			Id(input.repositoryStructVarName).Op("*").Qual(input.modelServicePackageName, input.repositoryStructName),
		)
}

func generateControllerConstructor(input usefulData) Code {
	return Func().
		Id(input.controllerStructConstructorName).
		Params(
			Id(input.repositoryStructVarName).Op("*").Qual(input.modelServicePackageName, input.repositoryStructName),
		).
		Op("*").Qual(input.modelServicePackageName, input.repositoryStructName).
		Block(
			Return(
				Op("&").Id(input.controllerStructName).Values(
					Dict{
						Id(input.repositoryStructVarName): Id(input.repositoryStructVarName),
					},
				),
			),
		)
}

func generateControllerSaveMethod(input usefulData) Code {
	return Func().
		Params(
			controllerReceiverParam(input),
		).
		Id(handlerMethodName(saveMethodKey)).
		Params(
			echoContextParam(),
		).
		Params(
			Error(),
		).
		Block(
			Var().Id(reqKeyword).Op("=").Add(input.modelStructQualifier).Values(),
			If(
				Err().Op(":=").Id("ctx").Dot("Bind").Call(
					Op("&").Id(reqKeyword),
				),
				Err().Op("!=").Nil(),
			).
				Block(
					Return(Err()),
				).Line(),
			If(
				Err().Op(":=").Id(ctxKeyword).Dot("Validate").Call(
					Op("&").Id(reqKeyword),
				),
				Err().Op("!=").Nil(),
			).
				Block(
					Return(Err()),
				).Line(),
			If(
				Err().Op(":=").Id(input.receiverVarName).Dot(input.repositoryStructVarName).Dot(saveMethodKey).Call(
					Op("&").Id(reqKeyword),
				),
				Err().Op("!=").Nil(),
			).Block(
				Return(Err()),
			),
			Return(
				Id(ctxKeyword).Dot("JSON").Call(Qual("http", "StatusCreated"), Op("&").Id(reqKeyword)),
			),
		)
}

func generateControllerGetById(input usefulData) Code {
	var (
		methodName      = fmt.Sprintf("Get%sById", input.modelStructName)
		inputStructName = fmt.Sprintf("%sInput", methodName)
	)

	return Type().
		Id(inputStructName).
		Struct(
			Id("Id").
				Add(input.idTypeAsJenCode).
				Tag(map[string]string{
					"param":    "id",
					"json":     "id",
					"validate": "required required_uuid",
				}),
		).
		Line().
		Line().
		Func().
		Params(
			controllerReceiverParam(input),
		).
		Id(handlerMethodName(methodName)).
		Params(echoContextParam()).
		Error().
		Block(
			Id(reqKeyword).Op(":=").Id(inputStructName).Values(),
			If(
				Err().Op(":=").Id("ctx").Dot("Bind").Call(Op("&").Id(reqKeyword)),
				Err().Op("!=").Nil(),
			).
				Block(
					Return(
						Err(),
					),
				),
			If(
				Err().Op(":=").Id(ctxKeyword).Dot("Validate").Call(Op("&").Id(reqKeyword)),
				Err().Op("!=").Nil(),
			).Block(
				Return(Err()),
			),
			Line(),
			List(Id(resKeyword), Err()).Op(":=").Id(input.receiverVarName).Dot(input.repositoryStructVarName).Dot(getByIdMethodKey).Call(
				Id(reqKeyword).Dot("Id"),
			),
			If(Err().Op("!=").Nil()).Block(
				Return(Err()),
			),
			Line(),
			Return(
				Id(ctxKeyword).Dot("JSON").Call(Qual("http", "StatusOK"), Op("&").Id(resKeyword)),
			),
		)
}

func generateControllerGetAllPaginatedMethods(input usefulData) Code {
	return Func().
		Params(controllerReceiverParam(input)).
		Id(handlerMethodName(getAllPaginatedMethodKey)).
		Params(echoContextParam()).
		Error().
		Block(
			Id(reqKeyword).Op(":=").Qual(winterRequestsQual, winterRequestsPageData).Values(),
			If(
				Err().Op(":=").Qual(winterQual, winterBindAndValidate).Call(Id(ctxKeyword), Op("&").Id(reqKeyword)),
				Err().Op("!=").Nil(),
			).Block(
				Return(Err()),
			),
			Line(),
			List(Id(resKeyword), Err()).Op(":=").Id(input.receiverVarName).Dot(input.repositoryStructVarName).Dot(getAllPaginatedMethodKey).Call(
				Id(reqKeyword).Dot("PageNumber"), Id(reqKeyword).Dot("PageSize"),
			),
			If(Err().Op("!=").Nil()).Block(
				Return(Err()),
			),
			Line(),
			Return(
				Id(ctxKeyword).Dot("JSON").Call(
					Qual("http", "StatusOK"),
					Op("&").Id(resKeyword),
				),
			),
		)
}

func handlerMethodName(name string) string {
	return fmt.Sprintf("%sHandler", name)
}

func echoContextParam() Code {
	return Id(ctxKeyword).Qual("github.com/labstack/echo/v4", "Context")
}

func controllerReceiverParam(input usefulData) Code {
	return Id(input.receiverVarName).Op("*").Id(input.controllerStructName)
}
