package main

import (
	. "github.com/dave/jennifer/jen"
	"github.com/rjNemo/underscore"
	"os"
)

const idKey = "Id"

type (
	EntityField struct {
		Name       string
		Type       string
		IsOptional bool
	}
	CreateEntityInput struct {
		EntityName string
		IsUuid     bool
		Fields     []EntityField
	}
)

func createEntityFile(data usefulData) error {
	jf := NewFile(data.modelsKey)
	jf.PackageComment("Code generated by creatore")

	jf.Add(generateEntityCode(data))

	return jf.Render(os.Stdout)
}

func generateEntityCode(input usefulData) Code {
	return Null().Type().Id(input.modelStructName).Struct(handleEntityFields(input.fields)...)
}

func handleEntityFields(fields []fieldMeta) []Code {
	return underscore.Map(fields, func(f fieldMeta) Code {
		builder := Null().Id(f.nameForStructAttribute)
		if f.field.IsOptional {
			builder.Qual("github.com/manicar2093/goption", "goption").Index(f.typeAsJenCode)
		} else {
			builder.Add(f.typeAsJenCode)
		}
		return builder.Tag(f.tags)
	})
}
